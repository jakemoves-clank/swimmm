// Regenerates src/lib/geo/torontoOutline.js — the city silhouette the map
// concepts draw on. Run by hand; Toronto's boundary changes about never, so
// this is deliberately not part of `npm run build` and its dependencies are
// deliberately not in package.json:
//
//   npm install --no-save topojson-server topojson-simplify topojson-client
//   node scripts/build-city-outline.mjs
//
// Source: City of Toronto Open Data, "Neighbourhoods" (158 polygons, EPSG:4326).
// The 158 neighbourhoods tile the city exactly, so dissolving them in TopoJSON
// — where shared arcs cancel — yields the municipal boundary without needing a
// separate boundary dataset. Visvalingam simplification then throws away
// ~96% of the points: at the sizes these concepts draw Toronto (300–700 px),
// anything finer is ink the reader can't resolve.
import { writeFileSync } from 'node:fs';
import { EnvHttpProxyAgent, fetch as undiciFetch } from 'undici';
import { topology } from 'topojson-server';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { merge } from 'topojson-client';

const SOURCE =
	'https://ckan0.cf.opendata.inter.prod-toronto.ca/dataset/fc443770-ef0a-4025-9c2c-2cb558bfab00/resource/0719053b-28b7-48ea-b863-068823a93aaa/download/neighbourhoods-4326.geojson';
const OUT = 'src/lib/geo/torontoOutline.js';

// Fraction of points kept by the Visvalingam pass. 0.08 holds the harbour,
// the Islands and the Humber mouth; 0.04 starts losing them.
const RETAIN = 0.08;
// Rings smaller than this (square degrees; ~8 ha) are dissolve artifacts —
// slivers where neighbourhood edges didn't quite line up — not geography.
const MIN_RING_AREA = 1e-5;
const COORD_DECIMALS = 4; // ~11 m; finer than the simplification anyway

function ringArea(ring) {
	let a = 0;
	for (let i = 0, n = ring.length, j = n - 1; i < n; j = i++) {
		a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
	}
	return Math.abs(a / 2);
}

const res = await undiciFetch(SOURCE, {
	dispatcher: new EnvHttpProxyAgent(),
	signal: AbortSignal.timeout(180_000)
});
if (!res.ok) throw new Error(`GET neighbourhoods -> ${res.status}`);
const neighbourhoods = await res.json();

const topo = presimplify(topology({ n: neighbourhoods }, 1e5));
const simplified = simplify(topo, quantile(topo, RETAIN));
const dissolved = merge(simplified, simplified.objects.n.geometries);

const rings = [];
for (const polygon of dissolved.coordinates) {
	for (const ring of polygon) {
		if (ringArea(ring) > MIN_RING_AREA) rings.push(ring);
	}
}
rings.sort((a, b) => ringArea(b) - ringArea(a));

const round = (v) => Number(v.toFixed(COORD_DECIMALS));
const coordinates = rings.map((ring) => [ring.map(([x, y]) => [round(x), round(y)])]);
const points = coordinates.flat(2).length;

writeFileSync(
	OUT,
	`// GENERATED by scripts/build-city-outline.mjs — do not edit by hand.
// City of Toronto Open Data, "Neighbourhoods" (EPSG:4326), 158 polygons
// dissolved to the municipal boundary and simplified to ${points} points.
export const TORONTO_OUTLINE = ${JSON.stringify({ type: 'MultiPolygon', coordinates })};
`
);
console.log(`wrote ${OUT}: ${coordinates.length} ring(s), ${points} points`);
